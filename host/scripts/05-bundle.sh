#!/usr/bin/env bash
# Stage 5: assemble the deliverables, producing both
#   dist/rvocs-tt-deps_<version>_<debarch>.tar.zst   offline bundle (driven by install.sh)
#   dist/rvocs-tt-deps_<version>_<debarch>.deb       Debian package (apt/dpkg, same payload)
# Both install the same system state; they differ in lifecycle management (see docs/INSTALL.md)
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

DEBARCH="$(arch_deb "$ARCH")"
NAME="${PKG_PREFIX}_${BUNDLE_VER}_${DEBARCH}"
B="$WORK_DIR/bundle/$NAME"
rm -rf "$B"
mkdir -p "$B"/{kmd,wheelhouse,systemd,udev,docs}

# ---------------------------------------------------------------- 1) shared payload
for f in install.sh verify.sh uninstall.sh hugepages-setup.sh; do
  [ -f "$REPO_ROOT/packaging/$f" ] || die "missing packaging/$f"
  install -m755 "$REPO_ROOT/packaging/$f" "$B/$f"
done
echo "$BUNDLE_VER" > "$B/VERSION"
cp "$REPO_ROOT/manifest.yaml" "$B/manifest.yaml" 2>/dev/null || true
cp "$REPO_ROOT/docs/INSTALL.md" "$B/docs/" 2>/dev/null || true
cp "$REPO_ROOT/docs/BUILD.md"   "$B/docs/" 2>/dev/null || true

{
  echo "# Targets supported by this bundle (generated by 05-bundle.sh)"
  echo "arch: $ARCH"
  echo "distros: $TARGETS"
  echo "kernels: ${KERNELS:-none}"
  echo "python:"
  for t in $TARGETS; do echo "  \"$t\": \"$(ubuntu_pyver "$t")\""; done
  echo "tools: $TOOLS"
} > "$B/target-matrix.yaml"

src="$(ls "$WORK_DIR"/kmd/tenstorrent-*.tar.gz 2>/dev/null | head -1)"
[ -n "$src" ] || die "missing the tt-kmd source tarball (run --stage kmd first)"
cp "$src" "$B/kmd/"
[ -d "$WORK_DIR/kmd/prebuilt" ] && cp -a "$WORK_DIR/kmd/prebuilt" "$B/kmd/"

for t in $TARGETS; do
  tag=$(pyver_tag "$(ubuntu_pyver "$t")")
  [ -d "$WORK_DIR/wheelhouse/$tag" ] || die "missing wheelhouse/$tag (run --stage wheels first)"
  mkdir -p "$B/wheelhouse/$tag"
  cp "$WORK_DIR/wheelhouse/$tag"/*.whl "$B/wheelhouse/$tag/" 2>/dev/null || die "wheelhouse/$tag is empty"
done

cp "$REPO_ROOT/packaging/systemd/"* "$B/systemd/" 2>/dev/null || die "systemd units missing"
cp "$REPO_ROOT/packaging/udev/"*    "$B/udev/"    2>/dev/null || die "udev rules missing"

# ---------------------------------------------------------------- 2) tar.zst
mkdir -p "$DIST_DIR"
TAR_OUT="$DIST_DIR/$NAME.tar.zst"
rm -f "$TAR_OUT" "$TAR_OUT.sha256"
log "packing tar.zst: $TAR_OUT"
tar -C "$WORK_DIR/bundle" -cf - "$NAME" | zstd -T0 -3 -q -o "$TAR_OUT"
( cd "$DIST_DIR" && sha256sum "$NAME.tar.zst" > "$NAME.tar.zst.sha256" )
log "  -> $(du -h "$TAR_OUT" | cut -f1)"

# ---------------------------------------------------------------- 3) .deb
DEB_NAME="$NAME.deb"
DEB_OUT="$DIST_DIR/$DEB_NAME"
D="$WORK_DIR/deb/${NAME}"
rm -rf "$D"
mkdir -p "$D/DEBIAN" "$D/opt/tt-deps"
cp -a "$B/." "$D/opt/tt-deps/"

# installed size in KiB, reported by dpkg
ISIZE="$(du -sk "$D/opt/tt-deps" | cut -f1)"

# Dependency list: base packages plus the runtime libraries required by the
# wheels built from source (riscv64 ships a source-built Pillow).
DEB_DEPS="dkms, build-essential, python3, python3-pip, python3-venv, zstd, systemd, udev"
case "$ARCH" in
  riscv64) DEB_DEPS="$DEB_DEPS, libtiff6, libjpeg-turbo8, liblcms2-2, libwebp7" ;;
esac

cat > "$D/DEBIAN/control" <<EOF
Package: tt-deps
Version: $BUNDLE_VER
Architecture: $DEBARCH
Maintainer: rvocs <rvocs@local>
Section: misc
Priority: optional
Installed-Size: $ISIZE
Depends: $DEB_DEPS
Recommends: linux-headers-generic
Conflicts: tt-smi, tt-flash, tt-topology
Description: Tenstorrent host dependencies (kernel driver, host tools, 1G hugepages)
 Installs the Tenstorrent kernel driver (DKMS or prebuilt module), the
 tt-smi / tt-flash / tt-topology command line tools (system-wide, no venv,
 no sudo required to run), persistent NUMA-aware 1G hugepages and udev rules.
 .
 Payload lives in /opt/tt-deps; the same content is also shipped as a
 self-contained tar.zst bundle. Both give the same installed system state.
EOF

install -m755 "$REPO_ROOT/packaging/deb/postinst" "$D/DEBIAN/postinst"
install -m755 "$REPO_ROOT/packaging/deb/prerm"    "$D/DEBIAN/prerm"
install -m755 "$REPO_ROOT/packaging/deb/postrm"   "$D/DEBIAN/postrm"

# prefer zstd (faster); fall back to xz when unsupported
ZOPT="-Zxz"
if dpkg-deb --help 2>&1 | grep -q 'zstd'; then ZOPT="-Zzstd"; fi
log "packing .deb: $DEB_OUT (compression $ZOPT)"
rm -f "$DEB_OUT" "$DEB_OUT.sha256"
( cd "$WORK_DIR/deb" && dpkg-deb --root-owner-group "$ZOPT" -b "$NAME" "$DEB_OUT" >/dev/null )
( cd "$DIST_DIR" && sha256sum "$DEB_NAME" > "$DEB_NAME.sha256" )
log "  -> $(du -h "$DEB_OUT" | cut -f1)"

log "bundle stage finished (tar.zst + deb)"
